CREATE TABLE ticket_closures (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reason TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL,
    ticket_id BIGINT NOT NULL,
    closed_by_id BIGINT NOT NULL,
    CONSTRAINT fk_ticket_closures_ticket_id FOREIGN KEY (ticket_id) REFERENCES tickets (id),
    CONSTRAINT fk_ticket_closures_closed_by_id FOREIGN KEY (closed_by_id) REFERENCES users (id)
);

CREATE INDEX idx_ticket_closures_ticket_id_created_at
    ON ticket_closures (ticket_id, created_at);
CREATE INDEX idx_ticket_closures_closed_by_id ON ticket_closures (closed_by_id);
