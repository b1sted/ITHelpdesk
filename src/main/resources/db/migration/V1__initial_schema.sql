CREATE TABLE departments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(150) NOT NULL,
    email VARCHAR(100) NOT NULL,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL,
    ticket_limit INTEGER NOT NULL DEFAULT 10,
    time_limit_hours INTEGER NOT NULL DEFAULT 24,
    department_id BIGINT NOT NULL,
    CONSTRAINT fk_users_department_id FOREIGN KEY (department_id) REFERENCES departments (id),
    CONSTRAINT ck_users_role CHECK (role IN ('EMPLOYEE', 'AGENT', 'MANAGER', 'ADMIN'))
);

CREATE UNIQUE INDEX ux_users_email_lower ON users (lower(email));
CREATE INDEX idx_users_role_full_name ON users (role, full_name);
CREATE INDEX idx_users_department_id ON users (department_id);

CREATE TABLE tickets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    description TEXT NOT NULL,
    status VARCHAR(30) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    resolved_at TIMESTAMP,
    closed_at TIMESTAMP,
    extension_hours INTEGER NOT NULL DEFAULT 0,
    version BIGINT NOT NULL DEFAULT 0,
    creator_id BIGINT NOT NULL,
    assignee_id BIGINT,
    category_id BIGINT NOT NULL,
    CONSTRAINT fk_tickets_creator_id FOREIGN KEY (creator_id) REFERENCES users (id),
    CONSTRAINT fk_tickets_assignee_id FOREIGN KEY (assignee_id) REFERENCES users (id),
    CONSTRAINT fk_tickets_category_id FOREIGN KEY (category_id) REFERENCES categories (id),
    CONSTRAINT ck_tickets_status CHECK (
        status IN ('NEW', 'IN_PROGRESS', 'WAITING_USER', 'ANSWERED', 'RESOLVED', 'CLOSED')
    )
);

CREATE INDEX idx_tickets_created_at ON tickets (created_at DESC);
CREATE INDEX idx_tickets_status_created_at ON tickets (status, created_at DESC);
CREATE INDEX idx_tickets_creator_id_created_at ON tickets (creator_id, created_at DESC);
CREATE INDEX idx_tickets_assignee_id_status_created_at
    ON tickets (assignee_id, status, created_at DESC);
CREATE INDEX idx_tickets_status_resolved_at ON tickets (status, resolved_at);
CREATE INDEX idx_tickets_category_id ON tickets (category_id);

CREATE TABLE messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    text TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL,
    ticket_id BIGINT NOT NULL,
    author_id BIGINT NOT NULL,
    CONSTRAINT fk_messages_ticket_id FOREIGN KEY (ticket_id) REFERENCES tickets (id),
    CONSTRAINT fk_messages_author_id FOREIGN KEY (author_id) REFERENCES users (id)
);

CREATE INDEX idx_messages_ticket_id_created_at ON messages (ticket_id, created_at);
CREATE INDEX idx_messages_author_id ON messages (author_id);

CREATE TABLE ticket_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL,
    reason TEXT NOT NULL,
    decision_comment VARCHAR(1000),
    created_at TIMESTAMP NOT NULL,
    decided_at TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    ticket_id BIGINT NOT NULL,
    requester_id BIGINT NOT NULL,
    target_assignee_id BIGINT,
    decided_by_id BIGINT,
    CONSTRAINT fk_ticket_requests_ticket_id FOREIGN KEY (ticket_id) REFERENCES tickets (id),
    CONSTRAINT fk_ticket_requests_requester_id FOREIGN KEY (requester_id) REFERENCES users (id),
    CONSTRAINT fk_ticket_requests_target_assignee_id
        FOREIGN KEY (target_assignee_id) REFERENCES users (id),
    CONSTRAINT fk_ticket_requests_decided_by_id FOREIGN KEY (decided_by_id) REFERENCES users (id),
    CONSTRAINT ck_ticket_requests_type CHECK (type IN ('RELEASE', 'REASSIGN')),
    CONSTRAINT ck_ticket_requests_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED'))
);

CREATE INDEX idx_ticket_requests_created_at ON ticket_requests (created_at DESC);
CREATE INDEX idx_ticket_requests_status_created_at ON ticket_requests (status, created_at DESC);
CREATE INDEX idx_ticket_requests_ticket_id_status ON ticket_requests (ticket_id, status);
CREATE INDEX idx_ticket_requests_requester_id ON ticket_requests (requester_id);
CREATE INDEX idx_ticket_requests_target_assignee_id ON ticket_requests (target_assignee_id);
CREATE INDEX idx_ticket_requests_decided_by_id ON ticket_requests (decided_by_id);

CREATE TABLE ticket_deadline_extensions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hours INTEGER NOT NULL,
    reason TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL,
    ticket_id BIGINT NOT NULL,
    created_by_id BIGINT NOT NULL,
    CONSTRAINT fk_ticket_deadline_extensions_ticket_id
        FOREIGN KEY (ticket_id) REFERENCES tickets (id),
    CONSTRAINT fk_ticket_deadline_extensions_created_by_id
        FOREIGN KEY (created_by_id) REFERENCES users (id)
);

CREATE INDEX idx_ticket_deadline_extensions_ticket_id_created_at
    ON ticket_deadline_extensions (ticket_id, created_at);
CREATE INDEX idx_ticket_deadline_extensions_created_by_id
    ON ticket_deadline_extensions (created_by_id);

CREATE TABLE support_settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auto_close_resolved_hours INTEGER NOT NULL DEFAULT 0
);

